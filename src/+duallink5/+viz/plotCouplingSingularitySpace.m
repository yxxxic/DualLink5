function [indices, results, sourceDirections, status, selectedQ, titles] = ...
        representativeResults( ...
        samples, options)
available = find(samples.theoreticalReachableMask);
if isempty(available)
    invalidInput();
end
indices = zeros(3, 1);
results = cell(3, 1);
sourceDirections = zeros(2, 3);
status = strings(3, 1);
selectedQ = zeros(3, 2);
titles = strings(3, 1);
sourceTensor = reshape(samples.passiveDirection, 2, []);
for index = 1:3
    [candidates, preferred] = representativeCandidates(samples, index);
    if isempty(candidates)
        candidates = available;
        preferred = false;
    end
    difference = [samples.thetaGrid(candidates) - ...
        options.representativeQ(index, 1), ...
        samples.phiGrid(candidates) - options.representativeQ(index, 2)];
    [~, localIndex] = min(sum(difference .^ 2, 2));
    indices(index) = candidates(localIndex);
    sourceDirections(:, index) = unitDirection( ...
        sourceTensor(:, indices(index)));
    q = [samples.thetaGrid(indices(index)), ...
        samples.phiGrid(indices(index))];
    selectedQ(index, :) = q;
    status(index) = samples.reasonMap(indices(index));
    titles(index) = representativeTitle(samples, indices(index), preferred);
    couplingOptions = struct( ...
        'collisionProfile', "none", 'topologyProfile', "none", ...
        'exactThreshold', samples.metadata.exactThreshold, ...
        'nearMetricThreshold', samples.metadata.nearMetricThreshold, ...
        'nearConditionThreshold', samples.metadata.nearConditionThreshold, ...
        'lowerBranchId', samples.metadata.lowerBranchId, ...
        'lowerBranchMode', "fixed", ...
        'referenceQ', samples.metadata.referenceQ);
    try
        result = duallink5.singularity.evaluateCoupling( ...
            q, options.geometry, couplingOptions);
    catch
        invalidInput();
    end
    if ~result.theoreticallyReachable || ...
            ~result.kinematics.quality.valid
        invalidInput();
    end
    unitDirection(result.coupling.passiveDirection);
    results{index} = result;
end
end

function [candidates, preferred] = representativeCandidates(samples, slot)
theoretical = samples.theoreticalReachableMask;
switch slot
    case 1
        mask = theoretical & samples.mechanicallyValidMask & ...
            ~samples.exactCouplingSingular & ...
            ~samples.nearCouplingSingular & ...
            ~samples.engineeringWarning;
    case 2
        mask = theoretical & samples.mechanicallyValidMask & ...
            samples.engineeringWarning & ~samples.exactCouplingSingular;
        if ~any(mask, 'all')
            mask = theoretical & samples.engineeringWarning & ...
                ~samples.exactCouplingSingular;
        end
    otherwise
        mask = theoretical & samples.exactCouplingSingular;
end
candidates = find(mask);
preferred = ~isempty(candidates);
end

function plotTitle = representativeTitle(samples, index, preferred)
if samples.exactCouplingSingular(index)
    label = "Exact coupling singularity";
elseif samples.nearCouplingSingular(index)
    label = "Near coupling singularity";
elseif samples.engineeringWarning(index)
    label = "Engineering warning";
elseif samples.safeUsableMask(index)
    label = "Regular";
elseif ~samples.mechanicallyValidMask(index)
    label = replace(lower(samples.reasonMap(index)), "_", " ");
    label = upper(extractBefore(label, 2)) + extractAfter(label, 1);
else
    label = "Theoretical configuration";
end
if preferred
    plotTitle = label + " representative";
else
    plotTitle = label + " (closest available)";
end
end

function direction = unitDirection(direction)
if ~(isnumeric(direction) && isreal(direction) && ...
        numel(direction) == 2 && all(isfinite(direction), 'all'))
    invalidInput();
end
direction = full(double(direction(:)));
magnitude = norm(direction);
if ~isfinite(magnitude) || magnitude < 1e-12
    invalidInput();
end
direction = direction / magnitude;
end

function [xValues, yValues] = assemblyCoordinates(assembly)
xValues = zeros(1, 0);
yValues = zeros(1, 0);
poses = {assembly.lower.points, assembly.upper.points};
for poseIndex = 1:numel(poses)
    names = fieldnames(poses{poseIndex});
    for nameIndex = 1:numel(names)
        point = poses{poseIndex}.(names{nameIndex});
        if isnumeric(point) && isreal(point) && numel(point) == 2 && ...
                all(isfinite(point), 'all')
            point = 1e3 * double(point(:));
            xValues(end + 1) = point(1); %#ok<AGROW>
            yValues(end + 1) = point(2); %#ok<AGROW>
        end
    end
end
end

function [xLimits, yLimits] = commonLimits(xValues, yValues)
xLimits = paddedRange(xValues);
yLimits = paddedRange(yValues);
end

function limits = paddedRange(values)
minimum = min(values);
maximum = max(values);
span = maximum - minimum;
padding = max(5, 0.08 * max(span, 1));
limits = [minimum - padding, maximum + padding];
end

function restoreAxes(axesHandles, originalNextPlot)
for index = 1:numel(axesHandles)
    if isgraphics(axesHandles(index), 'axes')
        axesHandles(index).NextPlot = char(originalNextPlot(index));
    end
end
end

